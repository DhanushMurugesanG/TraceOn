import { spawn, type ChildProcess } from 'node:child_process';
import { createConnection } from 'node:net';
import { mkdirSync, writeFileSync, openSync, closeSync } from 'node:fs';
import { join } from 'node:path';
import { TraceOnError } from '../../errors.js';

/** Default OTLP/HTTP port — adjacent to OTel's standard 4318 so we don't
 *  collide with a collector the user already runs. */
export const DEFAULT_OTLP_PORT = 4319;

export interface CollectorOptions {
  /** Path to the otelcol-contrib binary (from ensureCollectorBinary). */
  binaryPath: string;
  /** Directory for the generated config, output NDJSON files, and log. */
  dataDir: string;
  /** OTLP/HTTP receiver port. */
  port?: number;
  /** How long to wait for the receiver to accept connections. */
  readyTimeoutMs?: number;
  /** How long to wait after SIGTERM before escalating to SIGKILL. */
  shutdownGraceMs?: number;
}

export interface CollectorPaths {
  config: string;
  tracesFile: string;
  logsFile: string;
  logFile: string;
}

export function collectorPaths(dataDir: string): CollectorPaths {
  return {
    config: join(dataDir, 'collector.yaml'),
    tracesFile: join(dataDir, 'traces.ndjson'),
    logsFile: join(dataDir, 'logs.ndjson'),
    logFile: join(dataDir, 'collector.log'),
  };
}

/**
 * Two pipelines, one receiver: traces and logs each go to their own File
 * exporter so the embedded backend can read them independently (logs would
 * otherwise be silently dropped — SigNoz parity requires both).
 *
 * flush_interval is dropped to 200ms (default 1s) so the settle heuristic,
 * which polls the file every couple of seconds, sees fresh span counts.
 */
export function generateCollectorConfig(dataDir: string, port: number = DEFAULT_OTLP_PORT): string {
  const p = collectorPaths(dataDir);
  // Quote the path values as YAML double-quoted scalars (JSON.stringify is a
  // valid subset) so a dataDir containing a space, colon, or '#' can't break
  // the generated config.
  const tracesPath = JSON.stringify(p.tracesFile);
  const logsPath = JSON.stringify(p.logsFile);
  return `# Generated by TraceOn — do not edit; regenerated on every collector start.
receivers:
  otlp:
    protocols:
      http:
        endpoint: "127.0.0.1:${port}"

exporters:
  file/traces:
    path: ${tracesPath}
    format: json
    flush_interval: 200ms
  file/logs:
    path: ${logsPath}
    format: json
    flush_interval: 200ms

service:
  telemetry:
    metrics:
      level: none
  pipelines:
    traces:
      receivers: [otlp]
      exporters: [file/traces]
    logs:
      receivers: [otlp]
      exporters: [file/logs]
`;
}

/** True when something is already accepting connections on the port. */
export function isPortInUse(port: number, host = '127.0.0.1', timeoutMs = 500): Promise<boolean> {
  return new Promise((resolve) => {
    const socket = createConnection({ port, host });
    const done = (inUse: boolean) => {
      socket.destroy();
      resolve(inUse);
    };
    socket.setTimeout(timeoutMs);
    socket.once('connect', () => done(true));
    socket.once('timeout', () => done(false));
    socket.once('error', () => done(false));
  });
}

/**
 * Poll until the port accepts connections, the process dies, or we time out.
 * Exported for tests (driven against an in-test server, no collector needed).
 */
export async function waitForPortReady(
  port: number,
  opts: { timeoutMs: number; pollMs?: number; isProcessAlive?: () => boolean },
): Promise<void> {
  const pollMs = opts.pollMs ?? 150;
  const start = Date.now();
  while (Date.now() - start < opts.timeoutMs) {
    if (opts.isProcessAlive && !opts.isProcessAlive()) {
      throw new TraceOnError(
        'EMBEDDED_COLLECTOR_DOWN',
        'The embedded OTel collector exited during startup',
        'Check the collector log in the TraceOn data directory for the cause (bad config, port conflict, missing permissions).',
      );
    }
    if (await isPortInUse(port)) return;
    await new Promise((r) => setTimeout(r, pollMs));
  }
  throw new TraceOnError(
    'EMBEDDED_COLLECTOR_DOWN',
    `The embedded OTel collector did not become ready within ${opts.timeoutMs}ms`,
    'Check the collector log in the TraceOn data directory; if the machine is slow, raise the ready timeout in the embedded config.',
  );
}

/**
 * Owns one otelcol-contrib subprocess: writes the generated config, spawns,
 * waits until the OTLP port accepts connections, and tears down gracefully
 * (SIGTERM → grace window → SIGKILL). `stop()` is idempotent.
 *
 * Lifecycle ownership: the MCP server lazy-starts one of these on the first
 * embedded verify and stops it on server shutdown — mirroring SigNoz's
 * always-on availability without an extra always-on service.
 */
export class EmbeddedCollector {
  private child: ChildProcess | null = null;
  private spawnError: Error | null = null;
  readonly port: number;
  readonly paths: CollectorPaths;
  private readonly readyTimeoutMs: number;
  private readonly shutdownGraceMs: number;

  constructor(private readonly opts: CollectorOptions) {
    this.port = opts.port ?? DEFAULT_OTLP_PORT;
    this.paths = collectorPaths(opts.dataDir);
    this.readyTimeoutMs = opts.readyTimeoutMs ?? 10_000;
    this.shutdownGraceMs = opts.shutdownGraceMs ?? 3_000;
  }

  isAlive(): boolean {
    return this.child !== null && this.child.exitCode === null && this.child.signalCode === null;
  }

  async start(): Promise<void> {
    if (this.isAlive()) return;
    this.spawnError = null;

    if (await isPortInUse(this.port)) {
      throw new TraceOnError(
        'EMBEDDED_PORT_BUSY',
        `Port ${this.port} is already in use — cannot start the embedded collector`,
        `Something else (another collector? a previous TraceOn run?) is listening on ${this.port}. Stop it, or set a different port in the embedded config block.`,
      );
    }

    mkdirSync(this.opts.dataDir, { recursive: true });
    writeFileSync(this.paths.config, generateCollectorConfig(this.opts.dataDir, this.port));

    // Collector stdout/stderr go to a log file, NOT the MCP server's stdio —
    // stdout is the MCP protocol channel and must stay clean.
    const logFd = openSync(this.paths.logFile, 'a');
    try {
      this.child = spawn(this.opts.binaryPath, ['--config', this.paths.config], {
        stdio: ['ignore', logFd, logFd],
      });
    } catch (err) {
      throw new TraceOnError(
        'EMBEDDED_COLLECTOR_SPAWN_FAILED',
        'Failed to spawn the embedded OTel collector',
        `Tried to run ${this.opts.binaryPath}. Re-run \`traceon init\` to reinstall the collector binary. ${err instanceof Error ? err.message : ''}`.trim(),
        err,
      );
    } finally {
      closeSync(logFd);
    }

    // ENOENT / EACCES on a missing or non-executable binary are delivered
    // asynchronously as an 'error' event (the synchronous try/catch above
    // never sees them). Capture the cause so the readiness failure below can
    // report it, instead of pointing the user at an empty collector log.
    this.child.once('error', (err: Error) => {
      this.spawnError = err;
      this.child = null;
    });

    try {
      await waitForPortReady(this.port, {
        timeoutMs: this.readyTimeoutMs,
        isProcessAlive: () => this.isAlive(),
      });
    } catch (err) {
      // Cast: TS's control-flow analysis can't see the once('error') closure
      // mutating this.spawnError, so it narrows the field to null/never here.
      const spawnError = this.spawnError as Error | null;
      if (spawnError) {
        throw new TraceOnError(
          'EMBEDDED_COLLECTOR_SPAWN_FAILED',
          `Failed to spawn the embedded OTel collector: ${spawnError.message}`,
          `Tried to run ${this.opts.binaryPath}. Re-run \`traceon init\` to reinstall the collector binary.`,
          spawnError,
        );
      }
      throw err;
    }
  }

  /** SIGTERM, wait up to the grace window, then SIGKILL. Idempotent. */
  async stop(): Promise<void> {
    const child = this.child;
    if (!child || !this.isAlive()) {
      this.child = null;
      return;
    }
    this.child = null;

    await new Promise<void>((resolve) => {
      const killTimer = setTimeout(() => {
        child.kill('SIGKILL');
      }, this.shutdownGraceMs);
      child.once('exit', () => {
        clearTimeout(killTimer);
        resolve();
      });
      child.kill('SIGTERM');
    });
  }
}
